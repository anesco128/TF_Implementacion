    public void generarArchivoDeObjetosProyectos(ArrayList<Proyecto> datos) {
        if (!datos.isEmpty()) {
            ObjectOutputStream salida = null;
            try {
                salida = new ObjectOutputStream(new FileOutputStream("datosProyectos"));
                for (Proyecto p : datos) {
                    salida.writeObject(p);
                }
                JOptionPane.showMessageDialog(null, "Archivo datosProyectos generado: " + datos.size() + " proyecto(s)");
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Error almacenando los proyectos: " + e.getMessage());
            } finally {
                try {
                    salida.close();
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(null, "Error cerrando el archivo");
                }
            }
        } else {
            JOptionPane.showMessageDialog(null, "No hay proyectos para almacenar: la lista está vacía.");
        }
    }

    public ArrayList<Proyecto> leerArchivoDeObjetosProyectos() {
        ArrayList<Proyecto> datos = new ArrayList<>();
        ObjectInputStream entrada = null;
        try {
            entrada = new ObjectInputStream(new FileInputStream("datosProyectos"));
            boolean hayMas = true;
            while (hayMas) {
                try {
                    datos.add((Proyecto) entrada.readObject());
                } catch (EOFException e) {
                    hayMas = false;
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error recuperando los proyectos: " + e.getMessage());
        } finally {
            try {
                entrada.close();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Error cerrando el archivo");
            }
        }
        return datos;
    }

