    public String consultarTodosProyectos(ArrayList<Proyecto> datos) {
        String res = "";
        if (datos.isEmpty()) {
            res = "No hay proyectos registrados.";
        } else {
            res = "Los proyectos registrados son:\n\n";
            for (Proyecto p : datos) {
                res += p.toString() + " FechaFinalizacion: " + p.determinarFechaFinalizacion() + "\n\n";
            }
        }
        return res;
    }

    public String consultarProyectosEnCurso(ArrayList<Proyecto> datos) {
        String res = "";
        if (datos.isEmpty()) {
            res = "No hay proyectos registrados.";
        } else {
            for (Proyecto p : datos) {
                if (p.getEstado().equals("EN CURSO")) {
                    res += p.toString() + " FechaFinalizacion: " + p.determinarFechaFinalizacion() + "\n\n";
                }
            }
            if (res.isEmpty()) {
                res = "No hay proyectos en estado EN CURSO.";
            }
        }
        return res;
    }

