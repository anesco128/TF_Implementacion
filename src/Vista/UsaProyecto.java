    public String registrarIntegranteProyectoDadoCodigo(ArrayList<Proyecto> datos, String codigoProyecto) {
        String res;
        if (datos.isEmpty()) {
            res = "No hay proyectos registrados.";
        } else {
            Empleado elIntegrante = solicitarEmpleado();
            res = "No existe un proyecto con el código " + codigoProyecto;
            int i = 0;
            boolean encontrado = false;
            while (i < datos.size() && !encontrado) {
                if (datos.get(i).getCodigo().equals(codigoProyecto)) {
                    datos.get(i).agregarIntegrante(elIntegrante);
                    res = "Integrante registrado en el proyecto " + codigoProyecto;
                    encontrado = true;
                }
                i++;
            }
        }
        return res;
    }

    public String registrarEquipoProyectoDadoCodigo(ArrayList<Proyecto> datos, String codigoProyecto) {
        String res;
        if (datos.isEmpty()) {
            res = "No hay proyectos registrados.";
        } else {
            res = "No existe un proyecto con el código " + codigoProyecto;
            int i = 0;
            boolean encontrado = false;
            while (i < datos.size() && !encontrado) {
                Proyecto p = datos.get(i);
                if (p.getCodigo().equals(codigoProyecto)) {
                    int cantidad = 0;
                    do {
                        try {
                            cantidad = Integer.parseInt(leer("Cantidad de integrantes a registrar (mínimo 1):"));
                        } catch (NumberFormatException e) {
                            cantidad = 0;
                        }
                    } while (cantidad < 1);

                    ArrayList<Empleado> elEquipo = new ArrayList<>();
                    for (int k = 1; k <= cantidad; k++) {
                        JOptionPane.showMessageDialog(this, "Integrante " + k + " de " + cantidad);
                        elEquipo.add(solicitarEmpleado());
                    }
                    p.setSuEquipo(elEquipo);
                    res = "Equipo registrado en el proyecto " + codigoProyecto + ": " + cantidad + " integrante(s)";
                    encontrado = true;
                }
                i++;
            }
        }
        return res;
    }

    public String eliminarIntegranteProyectoDadoCodigo(ArrayList<Proyecto> datos, String codigoProyecto) {
        String res;
        if (datos.isEmpty()) {
            res = "No hay proyectos registrados.";
        } else {
            String elNumIde = leer("Número de identificación del integrante a eliminar:");
            res = "No existe un proyecto con el código " + codigoProyecto;
            int i = 0;
            boolean encontrado = false;
            while (i < datos.size() && !encontrado) {
                if (datos.get(i).getCodigo().equals(codigoProyecto)) {
                    Empleado elEliminado = datos.get(i).eliminarIntegrante(elNumIde);
                    if (elEliminado != null) {
                        res = "Integrante eliminado del proyecto " + codigoProyecto + ":\n" + elEliminado.toString();
                    } else {
                        res = "El empleado " + elNumIde + " no pertenece al equipo del proyecto " + codigoProyecto;
                    }
                    encontrado = true;
                }
                i++;
            }
        }
        return res;
    }

    public String actualizarEstadoProyectoDadoCodigo(ArrayList<Proyecto> datos, String codigoProyecto) {
        String res;
        if (datos.isEmpty()) {
            res = "No hay proyectos registrados.";
        } else {
            res = "No existe un proyecto con el código " + codigoProyecto;
            int i = 0;
            boolean encontrado = false;
            while (i < datos.size() && !encontrado) {
                if (datos.get(i).getCodigo().equals(codigoProyecto)) {
                    String elEstado;
                    do {
                        elEstado = leer("Nuevo estado (INICIADO, EN CURSO, CANCELADO, FINALIZADO, SUSPENDIDO, APLAZADO):")
                                .toUpperCase();
                    } while (!elEstado.equals("INICIADO") && !elEstado.equals("EN CURSO")
                            && !elEstado.equals("CANCELADO") && !elEstado.equals("FINALIZADO")
                            && !elEstado.equals("SUSPENDIDO") && !elEstado.equals("APLAZADO"));
                    datos.get(i).setEstado(elEstado);
                    res = "El proyecto " + codigoProyecto + " quedó en estado " + elEstado;
                    encontrado = true;
                }
                i++;
            }
        }
        return res;
    }

