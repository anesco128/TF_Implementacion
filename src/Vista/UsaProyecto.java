    public ArrayList<Cliente> leerArchivoDeObjetosClientes() {
        ArrayList<Cliente> datos = new ArrayList<>();
        ObjectInputStream entrada = null;
        try {
            entrada = new ObjectInputStream(new FileInputStream("datosClientes"));
            boolean hayMas = true;
            while (hayMas) {
                try {
                    Cliente elCliente = (Cliente) entrada.readObject();
                    // se guarda solo si no está repetido
                    boolean repetido = false;
                    for (Cliente c : datos) {
                        if (c.getNumeroIdentificacion().equals(elCliente.getNumeroIdentificacion())) {
                            repetido = true;
                        }
                    }
                    if (!repetido) {
                        datos.add(elCliente);
                    }
                } catch (EOFException e) {
                    hayMas = false;
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error recuperando los clientes: " + e.getMessage());
        } finally {
            try {
                if (entrada != null) {
                    entrada.close();
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error cerrando el archivo");
            }
        }
        return datos;
    }

